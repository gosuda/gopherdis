// parseAttributes parses RESP3 attribute maps ('|<len>\r\n').
func (rp *ReplyParser) parseAttributes(pCtx any) int {
	proto := rp.CurrLocation
	idx := bytes.IndexByte(proto[1:], '\r')
	if idx < 0 {
		return C_ERR
	}
	idx++
	length, err := strconv.ParseInt(string(proto[1:idx]), 10, 64)
	if err != nil {
		return C_ERR
	}
	rp.CurrLocation = proto[idx+2:]
	if rp.Callbacks.AttributeCallback != nil {
		rp.Callbacks.AttributeCallback(rp, pCtx, length, proto)
	}
	return C_OK
}

// parseVerbatimString parses RESP3 verbatim strings ('=<len>\r\n<format>:<string>\r\n').
func (rp *ReplyParser) parseVerbatimString(pCtx any) int {
	proto := rp.CurrLocation
	idx := bytes.IndexByte(proto[1:], '\r')
	if idx < 0 {
		return C_ERR
	}
	idx++
	bulkLen, err := strconv.ParseInt(string(proto[1:idx]), 10, 64)
	if err != nil {
		return C_ERR
	}
	rp.CurrLocation = proto[idx+2:]
	if int64(len(rp.CurrLocation)) < bulkLen+2 {
		return C_ERR
	}
	formatAndStr := rp.CurrLocation[:bulkLen]
	rp.CurrLocation = rp.CurrLocation[bulkLen+2:]
	protoLen := len(proto) - len(rp.CurrLocation)
	if rp.Callbacks.VerbatimStringCallback != nil {
		var format, str []byte
		if bulkLen >= 4 {
			format = formatAndStr[:3] // 3 bytes format e.g. "txt"
			str = formatAndStr[4:]    // skip colon
		} else {
			str = formatAndStr
		}
		rp.Callbacks.VerbatimStringCallback(pCtx, format, str, proto[:protoLen])
	}
	return C_OK
}

