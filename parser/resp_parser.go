// parseDouble parses RESP3 double replies (',<float>\r\n').
func (rp *ReplyParser) parseDouble(pCtx any) int {
	proto := rp.CurrLocation
	idx := bytes.IndexByte(proto[1:], '\r')
	if idx < 0 {
		return C_ERR
	}
	idx++
	rp.CurrLocation = proto[idx+2:]
	protoLen := len(proto) - len(rp.CurrLocation)
	val, err := strconv.ParseFloat(string(proto[1:idx]), 64)
	if err != nil {
		val = 0
	}
	if rp.Callbacks.DoubleCallback != nil {
		rp.Callbacks.DoubleCallback(pCtx, val, proto[:protoLen])
	}
	return C_OK
}

// parseBool parses RESP3 boolean replies ('#t\r\n' or '#f\r\n').
func (rp *ReplyParser) parseBool(pCtx any) int {
	proto := rp.CurrLocation
	idx := bytes.IndexByte(proto[1:], '\r')
	if idx < 0 {
		return C_ERR
	}
	idx++
	val := len(proto) > 1 && proto[1] == 't'
	rp.CurrLocation = proto[idx+2:]
	protoLen := len(proto) - len(rp.CurrLocation)
	if rp.Callbacks.BoolCallback != nil {
		rp.Callbacks.BoolCallback(pCtx, val, proto[:protoLen])
	}
	return C_OK
}

// parseArray parses array replies ('*<len>\r\n') or null array ('*-1\r\n').
func (rp *ReplyParser) parseArray(pCtx any) int {
	proto := rp.CurrLocation
	idx := bytes.IndexByte(proto[1:], '\r')
	if idx < 0 {
		return C_ERR
	}
	idx++
	length, err := strconv.ParseInt(string(proto[1:idx]), 10, 64)
	if err != nil {
		return C_ERR
	}
	rp.CurrLocation = proto[idx+2:]
	if length == -1 {
		protoLen := len(proto) - len(rp.CurrLocation)
		if rp.Callbacks.NullArrayCallback != nil {
			rp.Callbacks.NullArrayCallback(pCtx, proto[:protoLen])
		}
	} else {
		if rp.Callbacks.ArrayCallback != nil {
			rp.Callbacks.ArrayCallback(rp, pCtx, length, proto)
		}
	}
	return C_OK
}

