package parser

import (
	"bytes"
	"strconv"
)


/* ----------------------------------------------------------------------------------------
 * A RESP parser for parsing replies returned by RM_Call or Lua's 'redis.call()'.
 *
 * The parser introduces callbacks that need to be set by the user. Each
 * callback represents a different reply type. Each callback gets a ctx that
 * was given to the ParseReply function. The callbacks also give the protocol
 * (underlying blob) of the current reply and the size.
 *
 * Some callbacks also get the parser object itself:
 * - ArrayCallback
 * - SetCallback
 * - MapCallback
 * - AttributeCallback
 *
 * These callbacks need to continue parsing by calling ParseReply a number of
 * times, according to the supplied length. Subsequent ParseReply calls may use
 * a different ctx, which will be used for nested CallReply objects.
 *
 * These callbacks also do not receive a proto_len, which is not known at the
 * time of parsing. Callers may calculate it themselves after parsing the
 * entire collection.
 *
 * NOTE: This parser is designed to only handle replies generated by Redis
 * itself. It does not perform many required validations and thus NOT SAFE FOR
 * PARSING USER INPUT.
 * ----------------------------------------------------------------------------------------
 */

// parseBulk parses bulk string replies ('$<len>\r\n<data>\r\n') or null bulk string ('$-1\r\n').
func (rp *ReplyParser) parseBulk(pCtx any) int {
	proto := rp.CurrLocation
	idx := FindCR(proto[1:])
	if idx < 0 {
		return C_ERR
	}
	idx++ // offset adjusted for proto[1:]

	bulkLen, err := strconv.ParseInt(string(proto[1:idx]), 10, 64)
	if err != nil {
		return C_ERR
	}

	rp.CurrLocation = proto[idx+2:] // skip \r\n

	if bulkLen == -1 {
		// Null bulk string ('$-1\r\n')
		protoLen := len(proto) - len(rp.CurrLocation)
		if rp.Callbacks.NullBulkStringCallback != nil {
			rp.Callbacks.NullBulkStringCallback(pCtx, proto[:protoLen])
		}
	} else {
		// Bulk string data with trailing \r\n
		if int64(len(rp.CurrLocation)) < bulkLen+2 {
			return C_ERR
		}
		str := rp.CurrLocation[:bulkLen]
		rp.CurrLocation = rp.CurrLocation[bulkLen+2:] // skip bulkLen and \r\n
		protoLen := len(proto) - len(rp.CurrLocation)
		if rp.Callbacks.BulkStringCallback != nil {
			rp.Callbacks.BulkStringCallback(pCtx, str, proto[:protoLen])
		}
	}

	return C_OK
}

