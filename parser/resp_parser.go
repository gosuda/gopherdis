// ParseReply parses the RESP reply starting at rp.CurrLocation.
// It detects the reply type prefix byte and delegates to the corresponding parser method.
// Returns C_OK on success or C_ERR on failure.
func (rp *ReplyParser) ParseReply(pCtx any) int {
	if len(rp.CurrLocation) == 0 {
		if rp.Callbacks.Error != nil {
			rp.Callbacks.Error(pCtx)
		}
		return C_ERR
	}

	switch rp.CurrLocation[0] {
	case '$':
		return rp.parseBulk(pCtx)
	case '+':
		return rp.parseSimpleString(pCtx)
	case '-':
		return rp.parseError(pCtx)
	case ':':
		return rp.parseLong(pCtx)
	case '*':
		return rp.parseArray(pCtx)
	case '~':
		return rp.parseSet(pCtx)
	case '%':
		return rp.parseMap(pCtx)
	case '#':
		return rp.parseBool(pCtx)
	case ',':
		return rp.parseDouble(pCtx)
	case '_':
		return rp.parseNull(pCtx)
	case '(':
		return rp.parseBigNumber(pCtx)
	case '=':
		return rp.parseVerbatimString(pCtx)
	case '|':
		return rp.parseAttributes(pCtx)
	default:
		if rp.Callbacks.Error != nil {
			rp.Callbacks.Error(pCtx)
		}
		return C_ERR
	}
}


